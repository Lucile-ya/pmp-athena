# ── 辅助函数 ─────────────────────────────────────────────────────────

def _build_all() -> None:
    if not DOMAINS:
        _build_domains()

def get_domain(name: str) -> DomainKnowledge | None:
    """通过名称或其别名查找知识领域。"""
    _build_all()
    n = name.strip()
    # 精确匹配
    if n in DOMAINS:
        return DOMAINS[n]
    # 别名匹配
    for dm in DOMAINS.values():
        for alias in dm.aliases:
            if alias.lower() == n.lower() or alias in n or n in alias:
                return dm
    # 模糊匹配（关键词出现在领域名/别名中）
    for dm in DOMAINS.values():
        for alias in dm.aliases:
            if len(alias) >= 2 and alias in n:
                return dm
        if len(dm.name) >= 2 and dm.name in n:
            return dm
    return None

def guess_domain_from_query(text: str) -> str | None:
    """从查询文本中猜测目标知识领域。
    优先匹配标准领域名 + 别名；降级匹配名词子串。
    """
    _build_all()
    q = re.sub(r"(知识点|速查|总结|的考点|有哪些考点|考点\s*|详细|展开|全文|套路|情景|关联)\s*", "", text).strip()
    if not q:
        return None

    dm = get_domain(q)
    if dm:
        return dm.name

    # 降级：子串匹配
    q2 = q.replace("管理", "").strip()
    for dm in DOMAINS.values():
        name_short = dm.name.replace("管理", "").replace("/", "").replace("方法","").strip()
        if q2 in name_short or name_short in q2:
            return dm.name

    return None

def get_patterns_for_domain(domain_name: str) -> list[int]:
    """获取属于某知识领域的套路编号列表。"""
    _build_all()
    dm = get_domain(domain_name)
    if not dm:
        return []
    result: list[int] = []
    for pnum, domains in PATTERN_DOMAIN_MAP.items():
        if dm.name in domains:
            result.append(pnum)
    # 同时在别名匹配的领域中的套路也算
    for pnum, domains in PATTERN_DOMAIN_MAP.items():
        for dname in domains:
            d = get_domain(dname)
            if d and d.name == dm.name and pnum not in result:
                result.append(pnum)
    return sorted(result)

def get_related_domains(domain_name: str, top_n: int = 3) -> list[tuple[str, int, str]]:
    """获取某知识领域的关联领域（按关联强度排序）。"""
    _build_all()
    dm = get_domain(domain_name)
    if not dm:
        return []
    adj = DOMAIN_ADJACENCY.get(dm.name, [])
    return sorted(adj, key=lambda x: -x[1])[:top_n]

def get_sub_modules(domain_name: str) -> list[str]:
    """获取某知识领域的关键子模块/考点名称。"""
    _build_all()
    dm = get_domain(domain_name)
    if not dm:
        return []
    # 返回过程名 + 关键概念作为子模块
    result: list[str] = [p.name for p in dm.processes]
    result.extend(dm.key_concepts[:3])
    # 去重但保留顺序
    seen: set[str] = set()
    out: list[str] = []
    for r in result:
        if r not in seen:
            seen.add(r)
            out.append(r)
    return out

def list_all_domains() -> list[str]:
    """列出所有知识领域名。"""
    _build_all()
    return list(DOMAINS.keys())
