#!/usr/bin/env python3
"""用大王 7/31 早餐题样例跑批量判卷。"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY = r"d:\miniconda\python.exe"

# 题号后无空格 + 早餐题格式 + 我的答案
TEXT = r"""
41.一位高级副总裁要求创建更高效的团队来并行运行不同长度和复杂性的项目，这将影响项目经理能够投入到每个项目的时间量。项目经理通常将50%的时间用于项目，无论其复杂程度如何。作为服务型领导者，项目经理应该做什么来帮助实现这种转变？
A.审查组织过程资产(OPA)以评估类似项目风险的缓解计划
B.创建关于项目经理能力的风险条目并制定缓解计划
C.授权团队发展必要的技能以独立推进项目
D.根据增加的工作量发出变更请求以聘请额外的项目经理
答案：C
解析：授权团队掌握必要技能，适应 PM 时间投入减少。

42.一位项目经理正在管理一个将新软件部署到200个最终用户的项目。在实施过程中，有一个遗漏的过程导致一些用户丢失了他们的计算机数据。项目经理首先应该做什么？
A.与团队会面讨论根本原因并鼓励团队注意它并继续关注部署
B.记录此案例，直到最后的经验教训会议结束，以防止在实施过程中影响团队的士气
C.与团队成员会面并要求他们通过提供反馈作为经验教训来对案例进行审查
D.邀请顾问审查流程以避免重复相同的问题并与团队共享结果
答案：A
解析：问题已发生，先与团队找根本原因。

43.一位外部项目经理正在管理一家大公司新公司办公室的建设。项目管理计划指出，有必要聘请训练有素的外部资源来修改和验证重要的项目组成部分。客户拒绝聘请外部资源，因为成本高，即使它在项目预算之内。项目经理应该如何解决这个问题？
A.尝试通过调配其他项目的资源来在内部完成任务
B.约客户会面，说明任务不会执行
C.评估后果并与客户会面以解释可能的情况
D.雇用资源以实现项目目标
答案：C
解析：评估缺乏外部资源的影响，与客户沟通决策。

44.一个组织正在努力启动一个重要的项目。项目经理已确定范围定义是阻碍项目实施的主要因素。虽然大多数范围事项都是在利益相关者之间定义和商定的，但在这个阶段有一些事项很难掌握并且定义起来非常复杂。项目经理应该做什么？
A.建议使用预测方法交付定义明确的范围，并使用敏捷方法处理复杂事项
B.保持利益相关者在范围定义方面的动力，直到在开始项目之前实现完整的详细范围
C.建议将项目拆分为两个较小的项目，以便在不受预测方法干扰的情况下专门在敏捷环境中工作
D.更新风险登记册并将问题上报给项目管理办公室(PMO)，请求添加更多资源以帮助定义项目范围
答案：A
解析：已明确范围用预测，复杂部分用敏捷（混合）。

45.项目已满足商定的产品要求，即将结束。日程表还有剩余时间和超额预算，这些资源尚未计划转移到其他项目。一些产品拥护者希望继续为产品添加功能。项目经理应该做什么？
A.在不花费项目预算的情况下，使用剩余的时间和资源为项目增加额外的范围
B.通过将剩余的资源和时间用于产品的额外质量检查来确保产品质量
C.确认已满足项目关闭标准并释放剩余的预算和资源
D.获得发起人的批准，使用剩余预算向项目可交付成果添加额外功能
答案：D
解析：干系人提变更，需发起人/CCB 批准后再实施。

我的答案是：CCCAB
"""


def main() -> int:
    r = subprocess.run(
        [PY, str(ROOT / "pmp_athena" / "daily_practice.py"), "batch", "--stdin", "--json"],
        input=TEXT.encode("utf-8"),
        capture_output=True,
        cwd=str(ROOT),
    )
    sys.stdout.buffer.write(r.stdout)
    return r.returncode


if __name__ == "__main__":
    raise SystemExit(main())
